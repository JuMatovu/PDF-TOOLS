export const POPULAR_TOOLS = TOOLS.filter((t) => t.popular);

export const getToolBySlug = (slug: string): PDFTool | undefined => {
  return TOOLS.find((t) => t.slug === slug || t.route === `/tools/${slug}` || t.id === slug);
};

export const getToolsByCategory = (category: ToolCategory): PDFTool[] => {
  return TOOLS.filter((t) => t.category === category);
};
